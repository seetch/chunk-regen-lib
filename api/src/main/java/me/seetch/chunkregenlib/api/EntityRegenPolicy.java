package me.seetch.chunkregenlib.api;

/**
 * Определяет, что происходит с сущностями в чанке при регенерации.
 * Игроки в области действия регенератора не затрагиваются политикой напрямую —
 * см. RegenerationOptions#preservePlayers().
 */
public enum EntityRegenPolicy {

    /** Удалить всех не-игровых сущностей в чанке перед подстановкой новых данных. */
    REMOVE_ALL_NON_PLAYER,

    /** Оставить все сущности как есть, регенерации подвергается только рельеф/блоки/биомы. */
    KEEP_ALL,

    /** Оставить именованных (с custom name) и приручённых сущностей, остальных удалить. */
    KEEP_NAMED_OR_TAMED
}
