package me.seetch.chunkregenlib.api;

/**
 * Глубина генерации, до которой должен быть пересчитан чанк.
 *
 * Это обёртка над внутренней глубиной пайплайна ванильной генерации
 * (аналог ChunkStatus из NMS), не раскрывающая obfuscated/NMS-типы
 * в публичном API.
 */
public enum ChunkGenStage {

    /** Только шум/рельеф, без биомов поверхности и фич. */
    NOISE,

    /** Рельеф и поверхностные блоки (трава, песок и т.д.), без структур и растительности. */
    SURFACE,

    /** Поверхность плюс фичи и структуры (руды, деревья, подземелья и т.д.). */
    FEATURES,

    /** Полностью готовый чанк, как при первой генерации мира. */
    FULL
}
